// The plugin world, narrowed to the capabilities a plugin asks for.
//
// A JavaScript component imports every interface of the world it is built against, whether
// it calls it or not, and the host instantiates a plugin only if it granted every import. So
// the world a plugin is built against is its declaration of what it needs. `world` takes the
// package's WIT text and a list of capabilities and adds a world with those imports and all
// of `plugin`'s exports.

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Every capability of the `plugin` world, in the order the WIT lists them. */
export const CAPABILITIES = [
  'fs-read',
  'fs-write',
  'kernel',
  'events',
  'log',
  'clock',
  'random',
  'tools',
  'state',
  'service',
  'plugins',
  'llm',
  'secret',
  'http',
  'log-read',
  'session',
];

/** The WIT package version imports are qualified with. */
export const VERSION = '0.1.0';

/** The WIT text of the package as it is in this repository. */
export function defaultWit() {
  const here = dirname(fileURLToPath(import.meta.url));
  return readFileSync(join(here, '..', '..', '..', 'wit', 'corduroy.wit'), 'utf8');
}

/**
 * The package's WIT text with a world `name` added: the imports in `capabilities` and every
 * export of `plugin`.
 */
export function world(wit, capabilities, name = 'generated') {
  const unknown = capabilities.filter((capability) => !CAPABILITIES.includes(capability));
  if (unknown.length > 0) {
    throw new Error(`unknown capabilities: ${unknown.join(', ')} (known: ${CAPABILITIES.join(', ')})`);
  }
  const body = /\nworld plugin \{\n([\s\S]*?)\n\}/.exec(wit);
  if (!body) {
    throw new Error('the WIT text has no `world plugin`');
  }
  const kept = body[1]
    .split('\n')
    .filter((line) => {
      const imported = /^\s*import ([a-z-]+);/.exec(line);
      return !imported || capabilities.includes(imported[1]);
    })
    .join('\n');
  return `${wit}\n/// Generated by corduroy-plugin for: ${capabilities.join(', ') || 'no capabilities'}.\nworld ${name} {\n${kept}\n}\n`;
}

/** The module specifier a component imports `capability` under. */
export function specifier(capability) {
  return `corduroy:plugin/${capability}@${VERSION}`;
}
