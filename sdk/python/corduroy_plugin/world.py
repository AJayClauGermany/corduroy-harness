"""The plugin world, narrowed to the capabilities a plugin asks for.

A Python component imports every interface of the world it is built against, whether it
calls it or not, and the host instantiates a plugin only if it granted every import. So the
world a plugin is built against is its declaration of what it needs.
"""

import re
from pathlib import Path

#: Every capability of the `plugin` world, in the order the WIT lists them.
CAPABILITIES = [
    "fs-read",
    "fs-write",
    "kernel",
    "events",
    "log",
    "clock",
    "random",
    "tools",
    "state",
    "service",
    "plugins",
    "llm",
    "secret",
    "http",
    "log-read",
    "session",
]


def default_wit() -> str:
    """The WIT text of the package as it is in this repository."""
    return (Path(__file__).resolve().parents[3] / "wit" / "corduroy.wit").read_text()


def world(wit: str, capabilities: list[str], name: str = "generated") -> str:
    """The package's WIT text with a world `name` added: the imports in `capabilities` and
    every export of `plugin`."""
    unknown = [capability for capability in capabilities if capability not in CAPABILITIES]
    if unknown:
        raise ValueError(
            f"unknown capabilities: {', '.join(unknown)} (known: {', '.join(CAPABILITIES)})"
        )
    body = re.search(r"\nworld plugin \{\n([\s\S]*?)\n\}", wit)
    if body is None:
        raise ValueError("the WIT text has no `world plugin`")
    kept = [
        line
        for line in body.group(1).split("\n")
        if not (m := re.match(r"^\s*import ([a-z-]+);", line)) or m.group(1) in capabilities
    ]
    listed = ", ".join(capabilities) or "no capabilities"
    return f"{wit}\n/// Generated by corduroy-plugin for: {listed}.\nworld {name} {{\n" + "\n".join(kept) + "\n}\n"
