//! Skills the agent writes for itself, after Hermes.
//!
//! A skill is a directory holding a `SKILL.md`: a little front matter (`name`,
//! `description`) and a body describing how to do something. The agent creates one when it
//! has worked out a procedure worth keeping and patches it when the procedure turns out to
//! be wrong, so what it learns on one task is there for the next.
//!
//! * **Progressive disclosure.** Only an index (name and description) goes in the system
//!   prompt. The model loads a body with `skill_view` when a skill looks relevant.
//! * **Learning loop.** The plugin counts tool calls since the model last touched a skill.
//!   Once that passes `nudge_interval`, at the end of the turn it raises `skills/review-due`
//!   and adds a reminder to the prompt until a skill is saved.
//!
//! The plugin needs `fs-read` and `fs-write` scoped to its skills directory, and `events`
//! scoped to `skills/*`. It can reach nothing else.

mod skill;

/// Guest bindings for the `corduroy:plugin/plugin` world.
#[allow(
    clippy::all,
    clippy::pedantic,
    missing_docs,
    reason = "generated by wit-bindgen"
)]
mod bindings {
    wit_bindgen::generate!({
        path: "../../wit",
        world: "plugin",
        pub_export_macro: true,
    });
}

use std::fmt::Write as _;
use std::sync::{Mutex, MutexGuard, PoisonError};

use bindings::corduroy::plugin::types::{HostError, ToolSpec};
use bindings::corduroy::plugin::{events, fs_read, fs_write};
use bindings::{Event, Guest, PluginInfo, ToolError, Verdict};
use serde::Deserialize;

/// Plugin configuration, from the host.
#[derive(Deserialize)]
#[serde(default)]
struct Config {
    /// Directory the skills live in.
    dir: String,
    /// Tool calls without a skill being saved before the agent is nudged to review.
    nudge_interval: u32,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            dir: "skills".to_owned(),
            nudge_interval: 10,
        }
    }
}

/// What the plugin remembers between calls. It lives in the instance's memory, so it lasts
/// exactly as long as the plugin stays loaded.
struct State {
    config: Config,
    calls_since_skill: u32,
    review_due: bool,
}

static STATE: Mutex<Option<State>> = Mutex::new(None);

fn state() -> MutexGuard<'static, Option<State>> {
    STATE.lock().unwrap_or_else(PoisonError::into_inner)
}

fn dir() -> String {
    state()
        .as_ref()
        .map_or_else(|| Config::default().dir, |state| state.config.dir.clone())
}

#[derive(Deserialize)]
struct View {
    name: String,
}

#[derive(Deserialize)]
struct Manage {
    action: String,
    name: String,
    content: Option<String>,
    old_string: Option<String>,
    new_string: Option<String>,
}

/// The fields of a tool-result event this plugin cares about.
#[derive(Deserialize)]
struct ToolResult {
    tool: String,
}

struct Skills;

impl Guest for Skills {
    fn activate(config: String) -> Result<PluginInfo, String> {
        let config: Config =
            serde_json::from_str(&config).map_err(|error| format!("bad config: {error}"))?;
        *state() = Some(State {
            config,
            calls_since_skill: 0,
            review_due: false,
        });
        Ok(PluginInfo {
            name: "skills".to_owned(),
            version: env!("CARGO_PKG_VERSION").to_owned(),
            tools: specs(),
            subscriptions: vec!["tool/result".to_owned(), "turn/end".to_owned()],
            prompt: true,
            gates: Vec::new(),
        })
    }

    fn call_tool(name: String, input: String) -> Result<String, ToolError> {
        match name.as_str() {
            "skills_list" => Ok(list()),
            "skill_view" => view(&parse::<View>(&input)?.name),
            "skill_manage" => manage(&parse(&input)?),
            _ => Err(ToolError::UnknownTool(name)),
        }
    }

    fn on_event(event: Event) {
        let mut guard = state();
        let Some(state) = guard.as_mut() else {
            return;
        };
        match event.topic.as_str() {
            "tool/result" => {
                let own = serde_json::from_str::<ToolResult>(&event.payload)
                    .is_ok_and(|result| result.tool == "skill_manage");
                if !own {
                    state.calls_since_skill += 1;
                }
            }
            "turn/end" if state.calls_since_skill >= state.config.nudge_interval => {
                let calls = state.calls_since_skill;
                state.calls_since_skill = 0;
                state.review_due = true;
                drop(guard);
                // Without the `events` capability the reminder in the prompt still works.
                let _unheard =
                    events::emit("skills/review-due", &format!("{{\"tool_calls\":{calls}}}"));
            }
            _ => {}
        }
    }

    fn prompt_part() -> Option<String> {
        let review_due = state().as_ref().is_some_and(|state| state.review_due);
        let mut part = String::from(
            "Skills are procedures you saved earlier. Before starting a task, check the index \
             below and load any skill that looks relevant with skill_view(name). When you work \
             out a non-trivial workflow, save it with skill_manage(action=\"create\"); when a \
             skill turns out to be wrong or incomplete, fix it with \
             skill_manage(action=\"patch\").\n<available_skills>\n",
        );
        let index = index();
        if index.is_empty() {
            part.push_str("(none yet)\n");
        }
        for (name, description) in index {
            // Writing to a `String` cannot fail.
            let _ = writeln!(part, "- {name}: {description}");
        }
        part.push_str("</available_skills>");
        if review_due {
            part.push_str(
                "\n<skill_review>You have done a good deal of work since you last saved a \
                 skill. If any of it is a procedure you would want next time, save or patch a \
                 skill now.</skill_review>",
            );
        }
        Some(part)
    }

    /// Never called: this plugin guards no decision point.
    fn gate(_point: String, _request: String) -> Verdict {
        Verdict::Allow
    }
}

bindings::export!(Skills with_types_in bindings);

fn parse<'a, T: Deserialize<'a>>(input: &'a str) -> Result<T, ToolError> {
    serde_json::from_str(input).map_err(|error| ToolError::InvalidInput(error.to_string()))
}

impl From<HostError> for ToolError {
    fn from(error: HostError) -> Self {
        match error {
            HostError::Denied(reason) => Self::Denied(reason),
            HostError::Failed(reason) => Self::Failed(reason),
        }
    }
}

fn path(name: &str) -> String {
    format!("{}/{name}/SKILL.md", dir())
}

/// Every readable skill as `(name, description)`, sorted by name.
fn index() -> Vec<(String, String)> {
    // A missing directory simply means nothing has been saved yet.
    let entries = fs_read::list(&dir()).unwrap_or_default();
    entries
        .iter()
        .filter_map(|entry| entry.strip_suffix('/'))
        .filter_map(|name| {
            let contents = fs_read::read(&path(name)).ok()?;
            let meta = skill::front_matter(&contents).ok()?;
            Some((name.to_owned(), meta.description))
        })
        .collect()
}

fn list() -> String {
    let index = index();
    if index.is_empty() {
        return "No skills saved yet.".to_owned();
    }
    index
        .iter()
        .map(|(name, description)| format!("{name}: {description}"))
        .collect::<Vec<_>>()
        .join("\n")
}

fn view(name: &str) -> Result<String, ToolError> {
    skill::check_name(name).map_err(ToolError::InvalidInput)?;
    fs_read::read(&path(name)).map_err(|error| match error {
        HostError::Failed(_) => ToolError::Failed(format!("no skill named `{name}`")),
        denied @ HostError::Denied(_) => denied.into(),
    })
}

fn manage(args: &Manage) -> Result<String, ToolError> {
    let name = args.name.as_str();
    skill::check_name(name).map_err(ToolError::InvalidInput)?;
    let exists = fs_read::read(&path(name));
    let summary = match (args.action.as_str(), exists) {
        ("create", Ok(_)) => {
            return Err(ToolError::InvalidInput(format!(
                "skill `{name}` already exists; use action \"patch\" to change it"
            )));
        }
        ("create", Err(_)) => {
            let content = required(args.content.as_deref(), "content")?;
            save(name, content)?;
            format!("Created skill `{name}`.")
        }
        ("patch", Ok(current)) => {
            let content = match (&args.content, &args.old_string) {
                (Some(content), _) => content.clone(),
                (None, Some(old)) => {
                    let new = required(args.new_string.as_deref(), "new_string")?;
                    skill::patch(&current, old, new).map_err(ToolError::InvalidInput)?
                }
                (None, None) => {
                    return Err(ToolError::InvalidInput(
                        "patch needs either content or old_string and new_string".to_owned(),
                    ));
                }
            };
            save(name, &content)?;
            format!("Patched skill `{name}`.")
        }
        ("delete", Ok(_)) => {
            fs_write::remove(&path(name))?;
            format!("Deleted skill `{name}`.")
        }
        ("patch" | "delete", Err(_)) => {
            return Err(ToolError::Failed(format!("no skill named `{name}`")));
        }
        (other, _) => {
            return Err(ToolError::InvalidInput(format!(
                "unknown action `{other}`; use create, patch or delete"
            )));
        }
    };
    if let Some(state) = state().as_mut() {
        state.calls_since_skill = 0;
        state.review_due = false;
    }
    let payload = format!(
        "{{\"action\":{},\"name\":{}}}",
        serde_json::Value::from(args.action.as_str()),
        serde_json::Value::from(name)
    );
    // Telling the rest of the harness is a courtesy; the skill is saved either way.
    let _unheard = events::emit("skills/changed", &payload);
    Ok(summary)
}

fn required<'a>(value: Option<&'a str>, field: &str) -> Result<&'a str, ToolError> {
    value.ok_or_else(|| ToolError::InvalidInput(format!("`{field}` is required for this action")))
}

/// Validate a skill's contents against its name, then write it.
fn save(name: &str, content: &str) -> Result<(), ToolError> {
    skill::check_content(name, content).map_err(ToolError::InvalidInput)?;
    fs_write::write(&path(name), content)?;
    Ok(())
}

fn specs() -> Vec<ToolSpec> {
    // `(replay_safe, read_only)`. Listing and viewing change nothing, so they may be repeated
    // after a crash.
    let spec = |name: &str,
                (replay_safe, read_only): (bool, bool),
                description: &str,
                input_schema: &str| ToolSpec {
        name: name.to_owned(),
        description: description.to_owned(),
        input_schema: input_schema.to_owned(),
        replay_safe,
        read_only,
    };
    vec![
        spec(
            "skills_list",
            (true, true),
            "List every saved skill with its description.",
            r#"{"type":"object","properties":{}}"#,
        ),
        spec(
            "skill_view",
            (true, true),
            "Load a skill's full instructions. Do this before following or patching a skill.",
            r#"{"type":"object","properties":{"name":{"type":"string"}},"required":["name"]}"#,
        ),
        spec(
            "skill_manage",
            (false, false),
            "Create, patch or delete a skill. A skill is Markdown that starts with front \
             matter:\n---\nname: <the skill's name>\ndescription: <when to use it>\n---\n\
             followed by the procedure (When to Use, Procedure, Pitfalls, Verification). \
             Patch with old_string and new_string for a targeted fix, or with content to \
             rewrite the whole skill.",
            r#"{"type":"object","properties":{"action":{"type":"string","enum":["create","patch","delete"]},"name":{"type":"string","description":"Lowercase letters, digits, dots, dashes and underscores"},"content":{"type":"string","description":"Full SKILL.md text, for create or a whole rewrite"},"old_string":{"type":"string","description":"Text to replace; must occur exactly once"},"new_string":{"type":"string"}},"required":["action","name"]}"#,
        ),
    ]
}
