//! Write corduroy plugins in Rust.
//!
//! A plugin is a WebAssembly component built against the `corduroy:plugin/plugin` world in
//! `wit/corduroy.wit`. This crate generates the world's bindings once, so a plugin does not
//! repeat them, and supplies what every plugin would otherwise write for itself:
//!
//! * [`Plugin`], the world's exports as a trait in which everything but
//!   [`activate`](Plugin::activate) has a default: no tools, no prompt part, events ignored,
//!   no services, and a gate that denies (a gate that cannot answer fails closed).
//! * [`export!`], which makes a type implementing [`Plugin`] the component's exports.
//! * Builders for [`PluginInfo`] and [`ToolSpec`], [`parse`] and [`config`] for JSON, and
//!   `?` from a [`HostError`] to a [`ToolError`].
//! * The host interfaces, under [`host`]. Each is a capability, and a Rust plugin imports
//!   only those it calls, so the capabilities it needs are the host functions it uses.
//!
//! ```ignore
//! use corduroy_guest::{Plugin, PluginInfo, ToolError, ToolSpec, host};
//!
//! struct Hello;
//!
//! impl Plugin for Hello {
//!     fn activate(_config: String) -> Result<PluginInfo, String> {
//!         Ok(PluginInfo::new("hello", env!("CARGO_PKG_VERSION"))
//!             .tool(ToolSpec::new("hello", "Say hello", r#"{"type":"object"}"#).read_only()))
//!     }
//!
//!     fn call_tool(name: String, _input: String) -> Result<String, ToolError> {
//!         match name.as_str() {
//!             "hello" => Ok("hello".to_owned()),
//!             _ => Err(ToolError::UnknownTool(name)),
//!         }
//!     }
//! }
//!
//! corduroy_guest::export!(Hello);
//! ```
//!
//! A plugin crate is a `cdylib` built for `wasm32-unknown-unknown`; the host turns the module
//! into a component when it loads it. A panic is a trap that takes the instance down, so a
//! plugin returns errors instead.

use serde::de::DeserializeOwned;

/// Bindings for the `corduroy:plugin/plugin` world, generated by `wit-bindgen`.
#[allow(
    clippy::all,
    clippy::pedantic,
    missing_docs,
    unused_qualifications,
    reason = "generated by wit-bindgen"
)]
pub mod bindings {
    wit_bindgen::generate!({
        path: "../../wit",
        world: "plugin",
        pub_export_macro: true,
        default_bindings_module: "corduroy_guest::bindings",
    });
}

/// The host interfaces: one module per capability. Calling a function of one makes the
/// plugin import it, and the host instantiates the plugin only if it granted that capability.
pub use bindings::corduroy::plugin as host;
pub use bindings::corduroy::plugin::types::{
    CallError, Credential, Event, HostError, PluginInfo, ServiceCall, ToolError, ToolSpec, Verdict,
};

/// A plugin: the exports of the plugin world. Only [`activate`](Self::activate) has no
/// default. Export the type with [`export!`].
pub trait Plugin {
    /// Called once per instance with the plugin's configuration, JSON text. Says what the
    /// plugin contributes. Called again after a trap, on a fresh instance.
    ///
    /// # Errors
    ///
    /// A message saying why the plugin cannot start; the host records it and does not load
    /// the plugin.
    fn activate(config: String) -> Result<PluginInfo, String>;

    /// Run one of the tools listed by [`activate`](Self::activate). `input` is a JSON
    /// object. By default there are no tools.
    ///
    /// # Errors
    ///
    /// A [`ToolError`], which goes back to the model as an error result.
    fn call_tool(name: String, _input: String) -> Result<String, ToolError> {
        Err(ToolError::UnknownTool(name))
    }

    /// An event matching one of the plugin's subscriptions. Ignored by default.
    fn on_event(_event: Event) {}

    /// Text for the system prompt of the next model request. None by default.
    #[must_use]
    fn prompt_part() -> Option<String> {
        None
    }

    /// Decide at `point`, one of the decision points listed in
    /// [`PluginInfo::gates`]. By default the plugin guards nothing and is never asked; if it
    /// is, it denies, because a gate that cannot answer fails closed.
    #[must_use]
    fn gate(point: String, _request: String) -> Verdict {
        Verdict::Deny(format!("this plugin does not guard `{point}`"))
    }

    /// Answer a call to one of the services listed in [`PluginInfo::provides`]. By default
    /// the plugin provides none.
    ///
    /// # Errors
    ///
    /// A [`CallError`] for the caller.
    fn handle_call(call: ServiceCall) -> Result<String, CallError> {
        Err(CallError::Unknown(format!("service `{}`", call.service)))
    }
}

impl<T: Plugin> bindings::Guest for T {
    fn activate(config: String) -> Result<PluginInfo, String> {
        <T as Plugin>::activate(config)
    }

    fn call_tool(name: String, input: String) -> Result<String, ToolError> {
        <T as Plugin>::call_tool(name, input)
    }

    fn on_event(event: Event) {
        <T as Plugin>::on_event(event);
    }

    fn prompt_part() -> Option<String> {
        <T as Plugin>::prompt_part()
    }

    fn gate(point: String, request: String) -> Verdict {
        <T as Plugin>::gate(point, request)
    }

    fn handle_call(call: ServiceCall) -> Result<String, CallError> {
        <T as Plugin>::handle_call(call)
    }
}

/// Make `$ty`, a type implementing [`Plugin`], the exports of this component. Use it once,
/// in the plugin crate's root.
#[macro_export]
macro_rules! export {
    ($ty:ident) => {
        $crate::bindings::export!($ty with_types_in $crate::bindings);
    };
}

impl PluginInfo {
    /// A plugin called `name` that contributes nothing yet.
    #[must_use]
    pub fn new(name: &str, version: &str) -> Self {
        Self {
            name: name.to_owned(),
            version: version.to_owned(),
            tools: Vec::new(),
            subscriptions: Vec::new(),
            prompt: false,
            gates: Vec::new(),
            provides: Vec::new(),
        }
    }

    /// Offer `spec` to the model.
    #[must_use]
    pub fn tool(mut self, spec: ToolSpec) -> Self {
        self.tools.push(spec);
        self
    }

    /// Offer each of `specs` to the model.
    #[must_use]
    pub fn tools(mut self, specs: impl IntoIterator<Item = ToolSpec>) -> Self {
        self.tools.extend(specs);
        self
    }

    /// Receive events whose topic matches `pattern` (`*` matches any run of characters).
    #[must_use]
    pub fn subscribe(mut self, pattern: &str) -> Self {
        self.subscriptions.push(pattern.to_owned());
        self
    }

    /// Be asked for a [`Plugin::prompt_part`] before each model request.
    #[must_use]
    pub const fn with_prompt(mut self) -> Self {
        self.prompt = true;
        self
    }

    /// Be asked at the decision point `point`, such as `tool/call`, through
    /// [`Plugin::gate`].
    #[must_use]
    pub fn guard(mut self, point: &str) -> Self {
        self.gates.push(point.to_owned());
        self
    }

    /// Answer calls to the service `name` through [`Plugin::handle_call`].
    #[must_use]
    pub fn provide(mut self, name: &str) -> Self {
        self.provides.push(name.to_owned());
        self
    }
}

impl ToolSpec {
    /// A tool called `name`, with its description and the JSON Schema of its input as JSON
    /// text. It is neither replay-safe nor read-only until said so.
    #[must_use]
    pub fn new(name: &str, description: &str, input_schema: &str) -> Self {
        Self {
            name: name.to_owned(),
            description: description.to_owned(),
            input_schema: input_schema.to_owned(),
            replay_safe: false,
            read_only: false,
        }
    }

    /// Calling the tool twice is the same as calling it once, so after a crash the host may
    /// simply call it again.
    #[must_use]
    pub const fn replay_safe(mut self) -> Self {
        self.replay_safe = true;
        self
    }

    /// The tool only looks and changes nothing. Gates may let it through where they would
    /// ask about a tool that writes.
    #[must_use]
    pub const fn read_only(mut self) -> Self {
        self.read_only = true;
        self
    }
}

impl From<HostError> for ToolError {
    fn from(error: HostError) -> Self {
        match error {
            HostError::Denied(reason) => Self::Denied(reason),
            HostError::Failed(reason) => Self::Failed(reason),
        }
    }
}

/// A tool's JSON input as `T`.
///
/// # Errors
///
/// [`ToolError::InvalidInput`] saying what did not match, so the model can correct it.
pub fn parse<T: DeserializeOwned>(input: &str) -> Result<T, ToolError> {
    serde_json::from_str(input).map_err(|error| ToolError::InvalidInput(error.to_string()))
}

/// The plugin's configuration as `T`. Empty text is an empty object, so a plugin whose
/// configuration has defaults for everything starts without one.
///
/// # Errors
///
/// A message for [`Plugin::activate`] to return.
pub fn config<T: DeserializeOwned>(config: &str) -> Result<T, String> {
    let config = if config.trim().is_empty() {
        "{}"
    } else {
        config
    };
    serde_json::from_str(config).map_err(|error| format!("bad config: {error}"))
}

/// Record `message` on the event stream as `plugin/log`, at `level`. Needs the `log`
/// capability; a message the host refuses is dropped, since there is nowhere else to say so.
pub fn log(level: host::log::Level, message: &str) {
    drop(host::log::write(level, message));
}
